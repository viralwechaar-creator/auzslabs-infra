-- One-off remediation, not a numbered migration: after restoring the production database from a
-- backup onto the new droplet (Nov 2 2026 migration), several tables were missing columns that
-- "add column if not exists" migrations had added over time -- the backup predated some of them
-- even though later migrations (that created whole new tables) were present, a scattered gap, not
-- a clean cutoff. First caught live as "column u.deleted_at does not exist" blocking every sign-in.
-- This is every "alter table X add column if not exists ..." statement from the entire db/ history,
-- deduplicated -- safe to run any time, on any database, any number of times (every line is
-- IF NOT EXISTS). Run without -v ON_ERROR_STOP so one statement failing (e.g. a table that
-- genuinely doesn't exist on this install) doesn't block the rest from applying.
