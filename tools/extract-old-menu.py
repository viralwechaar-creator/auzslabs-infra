#!/usr/bin/env python3
"""Builds site/menu-old.css: the ORIGINAL side-menu styles (from the old theme.css + menu.css, commit eb7be68^)
scoped under #sidebarDrawer so no other stylesheet can change them. Owner rule: this menu never changes unless they ask."""
import re, subprocess, sys
def git(p): return subprocess.run(['git','show','eb7be68^:'+p],capture_output=True,text=True,cwd='/home/user/auzslabs-infra').stdout
KEYS = re.compile(r'sidebar|drawer|nav-link|nav-group|nav-sub|cart-count')
def parse(css):
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    i = 0; out = []
    while i < len(css):
        j = css.find('{', i)
        if j == -1: break
        head = css[i:j].strip(); depth = 1; k = j + 1
        while k < len(css) and depth:
            depth += {'{': 1, '}': -1}.get(css[k], 0); k += 1
        body = css[j+1:k-1]
        out.append((head, body)); i = k
    return out
def scope_sel(sel):
    parts = []
    for s in sel.split(','):
        s = s.strip()
        if not s: continue
        if s.startswith('.drawer-overlay') or s.startswith('html') or s.startswith(':root') or s.startswith('body'):
            parts.append(s)
        elif s.startswith('#sidebarDrawer'):
            parts.append(s)
        elif re.match(r'\.sidebar(?![\w-])', s):
            parts.append(re.sub(r'^\.sidebar', '#sidebarDrawer.sidebar', s, 1))
        else:
            parts.append('#sidebarDrawer ' + s)
    return ','.join(parts)
def rules(css):
    res = []
    for head, body in parse(css):
        if head.startswith('@media'):
            inner = [(h, b) for h, b in parse(body) if any(KEYS.search(x) for x in [h])]
            if inner: res.append('%s{%s}' % (head, ''.join('%s{%s}' % (scope_sel(h), b) for h, b in inner)))
        elif head.startswith('@'):
            continue
        elif KEYS.search(head):
            res.append('%s{%s}' % (scope_sel(head), body))
    return res
theme, menu = git('site/theme.css'), git('site/menu.css')
root = re.search(r':root\s*\{[^}]*\}', theme)
vars_ = root.group(0).replace(':root', '#sidebarDrawer,.drawer-overlay') if root else ''
reset = '#sidebarDrawer .nav-link,#sidebarDrawer .nav-group-toggle,#sidebarDrawer .nav-group-count,#sidebarDrawer .nav-group-indicator,#sidebarDrawer .nav-submenu,#sidebarDrawer .nav-submenu-inner,#sidebarDrawer .nav-sublink,#sidebarDrawer .sidebar-nav,#sidebarDrawer .sidebar-foot,#sidebarDrawer .sidebar-copy,#sidebarDrawer .nav-group,#sidebarDrawer .drawer-topbar,#sidebarDrawer .btn{all:revert}\n'
head = '/* THE ORIGINAL SIDE MENU. Generated by tools/extract-old-menu.py from the pre-redesign site. Do not edit by hand and do not change the look unless the owner asks. */\n'
extra = '#sidebarDrawer a{text-decoration:none!important}\n#sidebarDrawer .sidebar-foot .btn{text-decoration:none!important}\n@media(min-width:861px){#sidebarDrawer .sidebar-nav>a[href="products.html"]{order:3}#sidebarDrawer .sidebar-foot .btn{text-decoration:underline!important}}\n@media(max-width:860px){#sidebarDrawer .sidebar-nav>a[href="products.html"]{order:0}}\n.drawer-overlay{z-index:60}\n#sidebarDrawer.sidebar{z-index:61;transform:translateX(100%)}\n#sidebarDrawer.sidebar.open{transform:translateX(0)!important}\n'
open('/home/user/auzslabs-infra/site/menu-old.css','w').write(head + vars_ + '\n' + reset + '\n'.join(rules(theme)) + '\n' + '\n'.join(rules(menu)) + '\n' + extra)
print(len(rules(theme)), len(rules(menu)))
